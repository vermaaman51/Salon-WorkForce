CREATE TABLE employees (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, specialty VARCHAR(100) NOT NULL,
 phone VARCHAR(30) NOT NULL, shift_start TIME NOT NULL, shift_end TIME NOT NULL,
 working_days VARCHAR(30) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 CHECK (shift_end > shift_start)
);
CREATE TABLE appointments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES employees(id),
 customer VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
 service VARCHAR(100) NOT NULL, starts_at TIMESTAMP NOT NULL, ends_at TIMESTAMP NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'BOOKED', notes VARCHAR(1000) NOT NULL,
 CHECK (ends_at > starts_at), CHECK (status IN ('BOOKED','COMPLETED','CANCELLED'))
);
CREATE INDEX appointment_schedule ON appointments(employee_id, starts_at, ends_at);
CREATE TABLE leaves (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES employees(id), starts_on DATE NOT NULL,
 ends_on DATE NOT NULL, reason VARCHAR(500) NOT NULL, CHECK (ends_on >= starts_on)
);
CREATE TABLE queries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
 message VARCHAR(2000) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED'))
);
